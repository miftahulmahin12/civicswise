export function getQuestionsByVersion(version: "2025" | "2008") {
  return questions.filter((q) => q.version.includes(version));
}

export function getQuestionsByCategory(category: string) {
  return questions.filter((q) => q.category === category);
}

export function getSixtyFiveTwentyQuestions() {
  return questions.filter((q) => q.isSixtyFiveTwenty);
}

export function getQuestionById(id: string) {
  return questions.find((q) => q.id === id);
}

/** Draws a random, non-repeating set of questions for a practice session. */
export function drawPracticeSet(count: number, version: "2025" | "2008" = "2025") {
  const pool = getQuestionsByVersion(version);
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

